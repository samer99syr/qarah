export const createDefaultPageFromTemplate = (
  id: string,
  title: string,
  description: string,
  isMain: boolean,
  parentId: string | undefined,
  templateId: 'landmarks' | 'crafts' | 'history' | 'tourism' | 'assembly'
): CustomPage => {
  const preset = TEMPLATE_PRESETS.find(p => p.templateId === templateId);
  return {
    id,
    title,
    description,
    isMain,
    parentId,
    templateId,
    status: 'active',
    content: {
      introText: preset?.content.introText || 'مرحبا بكم في هذه الصفحة المخصصة.',
      sections: preset ? preset.content.sections.map(sec => ({
        ...sec,
        id: `sec_${id}_${Math.random().toString(36).substr(2, 9)}`
      })) : []
    }
  };
};
